mod ssh;

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    ssh::cleanup_ext_cache();
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_process::init())
        .manage(ssh::AppState::default())
        .invoke_handler(tauri::generate_handler![
            ssh::ssh_connect,
            ssh::ssh_disconnect,
            ssh::ssh_reconnect,
            ssh::ssh_alive,
            ssh::local_open,
            ssh::secret_set,
            ssh::secret_get,
            ssh::secret_delete,
            ssh::term_open,
            ssh::term_write,
            ssh::term_resize,
            ssh::term_close,
            ssh::sftp_home,
            ssh::sftp_realpath,
            ssh::sftp_list,
            ssh::sftp_mkdir,
            ssh::sftp_rename,
            ssh::sftp_remove,
            ssh::sftp_download,
            ssh::sftp_upload,
            ssh::profile_list,
            ssh::profile_save,
            ssh::profile_delete,
            ssh::default_download_dir,
            ssh::sys_stats,
            ssh::sftp_find,
            ssh::sftp_stat,
            ssh::sys_procs,
            ssh::proc_kill,
            ssh::sftp_copy,
            ssh::tmux_cwd,
            ssh::remote_chmod,
            ssh::remote_archive,
            ssh::remote_extract,
            ssh::key_generate,
            ssh::key_install,
            ssh::ssh_test,
            ssh::tunnel_start,
            ssh::tunnel_stop,
            ssh::log_candidates,
            ssh::log_start,
            ssh::log_stop,
            ssh::docker_list,
            ssh::docker_action,
            ssh::ext_apps,
            ssh::ext_open,
            ssh::ext_resolve,
            ssh::notify_os,
            ssh::ssh_config_hosts,
            ssh::sftp_read_text,
            ssh::sftp_write_text,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
